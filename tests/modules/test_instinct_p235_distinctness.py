"""P235 distinctness check: the named concepts (70 of 1000) must be distinct units,
not renamed duplicates of each other or of existing package modules."""
from __future__ import annotations

import importlib
import os
import unittest
from fractions import Fraction


class DistinctnessTest(unittest.TestCase):
    def setUp(self):
        from app.modules.instinct_doc import p235_concepts_registry as reg
        self.reg = reg

    def test_names_and_purposes_unique(self):
        names = [e["name"] for e in self.reg.ENTRIES]
        purposes = [e["purpose"] for e in self.reg.ENTRIES]
        self.assertEqual(len(names), len(set(names)), "duplicate concept names")
        self.assertEqual(len(purposes), len(set(purposes)),
                         "duplicate purposes: renamed duplicate concepts")

    def test_no_collision_with_existing_modules(self):
        pkg_dir = os.path.join(os.path.dirname(self.reg.__file__))
        existing = {f[:-3] for f in os.listdir(pkg_dir)
                    if f.endswith(".py") and not f.startswith("__")}
        for e in self.reg.ENTRIES:
            self.assertNotIn(e["name"], existing,
                             "concept %s collides with an existing module" % e["name"])
            for other in existing:
                if other.startswith("p235_concepts"):
                    continue
                self.assertNotEqual(e["name"], other)

    def test_every_entry_loadable_and_distinct_functions(self):
        funcs = []
        for e in self.reg.ENTRIES:
            mod = importlib.import_module(
                "app.modules.instinct_doc.p235_concepts_batch%d" % e["batch"])
            fn = getattr(mod, e["name"], None)
            self.assertTrue(callable(fn), "missing callable %s" % e["name"])
            funcs.append(fn)
        codes = {f.__code__ for f in funcs}
        self.assertEqual(len(codes), len(funcs),
                         "two concepts share one implementation object")

    def test_batch_sizes_and_doc_claims_honest(self):
        from collections import Counter
        counts = Counter(e["batch"] for e in self.reg.ENTRIES)
        self.assertTrue(all(c <= 10 for c in counts.values()))
        self.assertEqual(self.reg.IMPLEMENTED_SO_FAR, len(self.reg.ENTRIES))
        for claim in self.reg.DOC_CLAIMS:
            self.assertFalse(claim["asserted"])

