"""Experimenter-authored synthetic environments; independent matrix oracle.

Neither discovery nor baselines receive matrices or future outcomes.
"""
from random import Random
from formalism import P


def matmul(a, b):
    return [[sum(x*y for x,y in zip(row,col)) % P for col in zip(*b)] for row in a]


def nth(matrix, state, observation, n):
    # Powers of a transition matrix, not recurrence/quotient-ring code.
    d = len(matrix)
    acc = [[int(i == j) for j in range(d)] for i in range(d)]
    base = matrix
    while n:
        if n & 1:
            acc = matmul(acc, base)
        base = matmul(base, base)
        n //= 2
    final = [sum(a*b for a,b in zip(row,state)) % P for row in acc]
    return sum(a*b for a,b in zip(observation,final)) % P


def sequence(matrix, state, observation, count):
    values = []
    for _ in range(count):
        values.append(sum(a*b for a,b in zip(observation,state)) % P)
        state = [sum(a*b for a,b in zip(row,state)) % P for row in matrix]
    return values


def make_environment(seed, family, dimension):
    r = Random(seed)
    state = [r.randrange(P) for _ in range(dimension)]
    obs = [r.randrange(P) for _ in range(dimension)]
    if family == 'dense':
        matrix = [[r.randrange(P) for _ in state] for _ in state]
    elif family == 'diagonal':
        rates = r.sample(range(1, P), dimension)
        matrix = [[rates[i] if i == j else 0 for j in range(dimension)] for i in range(dimension)]
    elif family == 'jordan':
        rate = r.randrange(1, P)
        matrix = [[rate if i == j else int(j == i+1) for j in range(dimension)] for i in range(dimension)]
    else:
        raise ValueError(family)
    return matrix, state, obs


def switched_sequence(matrix_before, matrix_after, state, observation, count, switch_at):
    """Observe x_t then advance x_(t+1); switch transition matrix at t=switch_at.

    State stays continuous, no fabricated output perturbation. Prefix emissions
    through index switch_at are identical to the old regime. Later outputs are
    actually generated by the second matrix applied to the carried state.
    """
    if len(matrix_before) != len(matrix_after) or switch_at < 0:
        raise ValueError('matching dimensions and nonnegative switch index required')
    values = []
    for t in range(count):
        values.append(sum(a*b for a,b in zip(observation,state)) % P)
        matrix = matrix_before if t < switch_at else matrix_after
        state = [sum(a*b for a,b in zip(row,state)) % P for row in matrix]
    return values
